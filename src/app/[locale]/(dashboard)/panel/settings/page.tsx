//= Components
import SettingsWrapper from '@/components/Panel/Content/Settings/Wrapper';
//= I18n
import getDictionary from "@/dictionaries/serverDictionary";
//= Types
import type { Locale, Dictionary } from '@/types';

export async function generateMetadata(props: { params: Promise<{ locale: Locale }> }) {
  const params = await props.params;

  const {
    locale
  } = params;

  const { translations: dictionary } = await getDictionary();

  return {
    title: `${locale === 'ar' ? 'فلاتر كامب' : 'FlutterCamp'} - ${dictionary.panel.sidemenu.dashboard} | ${dictionary.panel.sidemenu.settings}`,
    description: 'FlutterCamp is an lms created by grids apps',

  }
}

async function Panel(props: { params: Promise<{ locale: Locale }> }) {
  const params = await props.params;

  const {
    locale
  } = params;

  const { translations: dictionary } = await getDictionary();

  return (
    <>
      <SettingsWrapper translations={(dictionary as Dictionary).panel.settings} locale={locale} />
    </>
  )
}

export default Panel;
